  /// 提取日记中的成语
  static Map<String, int> extractIdioms(List<Diary> diaries) {
    final Map<String, int> idiomCount = {};
    
    for (final diary in diaries) {
      if (diary.content == null || diary.content!.isEmpty) continue;
      
      final content = diary.content!;
      
      // 检查每个成语是否出现在内容中
      for (final idiom in _commonIdioms) {
        if (content.contains(idiom)) {
          idiomCount[idiom] = (idiomCount[idiom] ?? 0) + 1;
        }
      }
    }
    
    // 按频率排序
    final sortedEntries = idiomCount.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    
    return Map.fromEntries(sortedEntries);
  }
  
  /// 分析日记心情
  static Map<String, int> analyzeMood(List<Diary> diaries) {
    final Map<String, int> moodCount = {
      'happy': 0,
      'sad': 0,
      'angry': 0,
      'anxious': 0,
      'peaceful': 0,
      'grateful': 0,
      'hopeful': 0,
      'lonely': 0,
      'tired': 0,
      'surprised': 0,
    };
    
    for (final diary in diaries) {
      if (diary.content == null || diary.content!.isEmpty) continue;
      
      final content = diary.content!.toLowerCase();
      
      for (final entry in _moodKeywords.entries) {
        for (final keyword in entry.value) {
          if (content.contains(keyword)) {
            moodCount[entry.key] = (moodCount[entry.key] ?? 0) + 1;
            break; // 每种心情只计一次
          }
        }
      }
    }
    
    // 移除计数为0的心情
    moodCount.removeWhere((key, value) => value == 0);
    
    return moodCount;
  }
  

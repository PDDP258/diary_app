  /// 分析写作习惯
  static Map<String, dynamic> analyzeWritingHabits(List<Diary> diaries) {
    if (diaries.isEmpty) return {};
    
    // 计算平均日记长度
    final avgLength = diaries.fold<int>(0, (sum, d) => sum + d.wordCount) / diaries.length;
    
    // 找出最长和最短日记
    final sortedByLength = List<Diary>.from(diaries)
      ..sort((a, b) => b.wordCount.compareTo(a.wordCount));
    
    return {
      'avgLength': avgLength.toStringAsFixed(0),
      'longestDiary': sortedByLength.first,
      'shortestDiary': sortedByLength.last,
      'totalDiaries': diaries.length,
    };
  }
